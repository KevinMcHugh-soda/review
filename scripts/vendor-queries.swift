#!/usr/bin/env swift
//
// vendor-queries.swift — turn scripts/queries/*.scm into Swift string literals
// in Sources/ReviewSyntax/Queries/.
//
// The highlight queries are compiled into the binary rather than loaded from
// the grammar packages' resource bundles; plans/code-viewer.md says why. To
// update them, replace the .scm files from the grammar repositories at the
// versions Package.resolved pins, then run `swift scripts/vendor-queries.swift`.

import Foundation

struct Source {
    let file: String
    let constant: String
    /// The upstream repository, tag and path the file was copied from.
    let origin: String
}

let sources = [
    Source(file: "go-highlights.scm", constant: "goHighlights", origin: "tree-sitter-go v0.25.0, queries/highlights.scm"),
    Source(file: "javascript-highlights.scm", constant: "javaScriptHighlights", origin: "tree-sitter-javascript v0.23.1, queries/highlights.scm"),
    Source(file: "javascript-jsx-highlights.scm", constant: "jsxHighlights", origin: "tree-sitter-javascript v0.23.1, queries/highlights-jsx.scm"),
    Source(file: "typescript-highlights.scm", constant: "typeScriptHighlights", origin: "tree-sitter-typescript v0.23.2, queries/highlights.scm"),
    Source(file: "json-highlights.scm", constant: "jsonHighlights", origin: "tree-sitter-json v0.24.8, queries/highlights.scm"),
    Source(file: "yaml-highlights.scm", constant: "yamlHighlights", origin: "tree-sitter-yaml v0.7.0 (tree-sitter-grammars), queries/highlights.scm"),
]

var output = """
// Generated by scripts/vendor-queries.swift — do not edit by hand.
//
// Highlight queries from the tree-sitter grammar repositories, MIT licensed;
// see ThirdPartyLicenses/.

enum VendoredQueries {

"""

for source in sources {
    let text = try String(contentsOfFile: "scripts/queries/\(source.file)", encoding: .utf8)
    precondition(!text.contains("\"\"\"#"), "\(source.file) would end the raw string early")
    output += """
        /// \(source.origin)
        static let \(source.constant) = #\"\"\"
    \(text.split(separator: "\n", omittingEmptySubsequences: false).map { $0.isEmpty ? "" : "    \($0)" }.joined(separator: "\n"))
        \"\"\"#


    """
}
output = output.trimmingCharacters(in: .newlines) + "\n}\n"

try output.write(toFile: "Sources/ReviewSyntax/Queries/VendoredQueries.swift", atomically: true, encoding: .utf8)
print("✓ wrote Sources/ReviewSyntax/Queries/VendoredQueries.swift")
